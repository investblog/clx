#!/usr/bin/env node
// node scripts/build-mcp.mjs [--check] — the MCP tools' descriptions and argument schemas
// (src/mcp/schemas.gen.ts) from docs/openapi.yaml and the table of src/mcp/table.ts (ADR 0023): a
// tool says what its /v1 call's contract says. The file is committed, so a review sees every change
// to what agents are offered; `--check` fails if it is not what the contract makes now (`build` and
// `deploy` run it).
import fs from 'node:fs';
import { parse } from 'yaml';
import { TABLE } from '../src/mcp/table.ts';

const OUT = 'src/mcp/schemas.gen.ts';
const doc = parse(fs.readFileSync('docs/openapi.yaml', 'utf8'));

/** A schema with every `$ref` of the contract in place. */
function resolve(v) {
  if (Array.isArray(v)) return v.map(resolve);
  if (!v || typeof v !== 'object') return v;
  if (typeof v.$ref === 'string') return resolve(v.$ref.slice(2).split('/').reduce((o, k) => o[k], doc));
  return Object.fromEntries(Object.entries(v).map(([k, x]) => [k, resolve(x)]));
}

const MUTATING = new Set(['POST', 'PUT', 'PATCH', 'DELETE']);

export function build() {
  const out = {};
  for (const t of TABLE) {
    const op = doc.paths[t.path.replace(/^\/v1/u, '/v1')]?.[t.method.toLowerCase()];
    if (!op) throw new Error(`${t.name}: ${t.method} ${t.path} is not in docs/openapi.yaml`);
    const properties = {};
    const required = [];
    const query = [];
    for (const p of (op.parameters ?? []).map(resolve)) {
      if (p.in === 'header') continue;
      properties[p.name] = { ...p.schema, ...(p.description ? { description: p.description } : {}) };
      if (p.required) required.push(p.name);
      if (p.in === 'query') query.push(p.name);
    }
    const body = resolve(op.requestBody?.content?.['application/json']?.schema);
    const fields = Object.keys(body?.properties ?? {});
    for (const [k, s] of Object.entries(body?.properties ?? {})) properties[k] = s;
    required.push(...(body?.required ?? []));
    if (MUTATING.has(t.method))
      properties.idempotency_key = {
        ...resolve(doc.components.parameters.IdempotencyKey).schema,
        description: 'Sent as the Idempotency-Key: the same key and arguments within 24 hours return the first answer and change nothing again. Without one the server makes one, and a repeated call is not protected.',
      };
    const description = [op.summary, op.description].filter(Boolean).join('\n\n').trim();
    out[t.name] = {
      description,
      inputSchema: { type: 'object', properties, ...(required.length ? { required } : {}), additionalProperties: false },
      query,
      body: fields,
    };
  }
  return `// Generated by scripts/build-mcp.mjs from docs/openapi.yaml and src/mcp/table.ts — do not edit.\n/* eslint-disable */\nexport const SCHEMAS: Record<string, { description: string; inputSchema: Record<string, unknown>; query: string[]; body: string[] }> = ${JSON.stringify(out, null, 2)};\n`;
}

if (process.argv[1]?.replace(/\\/gu, '/').endsWith('scripts/build-mcp.mjs')) {
  const file = build();
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(OUT) || fs.readFileSync(OUT, 'utf8') !== file) throw new Error(`${OUT} is not what docs/openapi.yaml makes: run node scripts/build-mcp.mjs`);
    console.log(`${OUT} is current`);
  } else {
    fs.writeFileSync(OUT, file);
    console.log(`${OUT}: ${TABLE.length} tools`);
  }
}
